#!/usr/bin/env python3
"""Writes tests/uRigFixtures.pas : the rest transformation (translation, rotation)
of the bones of the models, read from the glb files. Used by TestPose.pas.

Usage: python3 make_fixtures.py ghwmaq.glb GHWBodyModel.glb
The bone lists must be the same as the profiles in src/uPoseRig.pas.
"""
import json
import struct
import sys

PROFILES = {
    "Ghwmaq": ["bone", "pelvis", "l.leg", "l.leg2", "l.leg3", "r.leg", "r.leg2", "r.leg3", "spine1", "spine2",
               "l.arm1", "l.arm2", "l.hand", "r.arm1", "r.arm2", "r.hand", "neck", "head"],
    "GhwBody": ["Spine001", "Pelvis L", "Thigh L", "Shin L", "Foot L", "Pelvis R", "Thigh R", "Shin R", "Foot R",
                "Spine002", "Spine003", "Spine004", "Spine005", "Spine006",
                "Shoulder L", "Upper Arm L", "Forearm L", "Hand L",
                "Shoulder R ", "Upper Arm R ", "Forearm R", "Hand R", "Neck", "Head"],
}


def load(path):
    d = open(path, "rb").read()
    jl, _ = struct.unpack_from("<II", d, 12)
    return json.loads(d[20:20 + jl])


def main(ghwmaq, ghwbody):
    out = ["unit uRigFixtures;", "", "// Generated by make_fixtures.py from the glb files. Do not edit.", "",
           "interface", "", "uses uPoseSolver, uPoseRig;", "", "type", "  TStringArray = array of string;", ""]
    for name in PROFILES:
        out.append("function %sRest : TRigRestArray;" % name)
        out.append("function %sParents : TStringArray;" % name)
    out += ["", "implementation", ""]
    for name, path in (("Ghwmaq", ghwmaq), ("GhwBody", ghwbody)):
        doc = load(path)
        by = {n["name"]: n for n in doc["nodes"]}
        out.append("function %sRest : TRigRestArray;" % name)
        out.append("begin")
        out.append("  SetLength(Result, %d);" % len(PROFILES[name]))
        for i, bone in enumerate(PROFILES[name]):
            n = by[bone]
            t = n.get("translation", [0, 0, 0])
            r = n.get("rotation", [0, 0, 0, 1])
            out.append("  Result[%d].Translation := Vec3(%.7f, %.7f, %.7f);  // %s" % (i, t[0], t[1], t[2], bone))
            out.append("  Result[%d].Rotation.X := %.7f; Result[%d].Rotation.Y := %.7f; "
                       "Result[%d].Rotation.Z := %.7f; Result[%d].Rotation.W := %.7f;" % (i, r[0], i, r[1], i, r[2], i, r[3]))
        out += ["end;", ""]
        # The real parent node of each bone in the glb
        parent_of = {}
        for n in doc["nodes"]:
            for c in n.get("children", []):
                parent_of[doc["nodes"][c]["name"]] = n["name"]
        out.append("function %sParents : TStringArray;" % name)
        out.append("begin")
        out.append("  SetLength(Result, %d);" % len(PROFILES[name]))
        for i, bone in enumerate(PROFILES[name]):
            out.append("  Result[%d] := '%s';  // parent of %s" % (i, parent_of.get(bone, ""), bone))
        out += ["end;", ""]
    out.append("end.")
    open("uRigFixtures.pas", "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
